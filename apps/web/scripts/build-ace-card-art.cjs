#!/usr/bin/env node
"use strict";
/**
 * TANVION ROYALE — Royale Ace card-art builder (pack-ready, NOT YET RUN).
 *
 * Waits for YOU to unzip the deck at:
 *   apps/web/public/games/royale-ace/cards-src/Playing Cards/SVG-cards-1.3/*.svg
 *   apps/web/public/games/royale-ace/cards-src/Playing Cards/PNG-cards-1.3/*.png
 *
 * When the pack is present, this script:
 *   1. reads the SVGs, optimizes (svgo if installed, else regex pass), strips
 *      inkscape/sodipodi/rdf editor metadata,
 *   2. inspects each candidate (court-figure vs plain big-suit) and writes the
 *      verified mapping table to stdout + `art/MAPPING.md`,
 *   3. emits our symbol set into `src/games/royale-ace/art/`:
 *      ace/king/queen/jack (court portrait panel, mirrored index dropped) and
 *      spade/heart/diamond/club (single big centered suit), each as a React
 *      component with suit colors from CSS vars (--ra-red-suit etc.) while
 *      court palettes stay fixed,
 *   4. renders @1x/@2x WebP fallbacks for the sprite atlas (needs `sharp` or
 *      system resvg+cwebp; skipped with a warning otherwise),
 *   5. flips `ACE_ART_PLACEHOLDER` to false via the adapter (manual confirm).
 *
 * Until the pack lands it exits 0 with "PACK MISSING — placeholders stay".
 * Game logic, math, RTP, wallet, admin, DB untouched (visual only).
 * Cross-platform Node (no bash). Run: node scripts/build-ace-card-art.mjs
 */
const fs = require("fs");
const path = require("path");

const web = path.join(__dirname, "..");
const SRC_DIR = path.join(web, "public", "games", "royale-ace", "cards-src", "Playing Cards");
const SVG_DIR = path.join(SRC_DIR, "SVG-cards-1.3");
const PNG_DIR = path.join(SRC_DIR, "PNG-cards-1.3");
const ART_DIR = path.join(web, "src", "games", "royale-ace", "art");

// Expected mapping per the brief (verified at build time by inspection).
// `2`-suffixed files may be court OR plain — the inspector below decides.
const WANT = {
  ace: ["ace_of_spades.svg"],
  king: ["king_of_hearts2.svg", "king_of_hearts.svg"],
  queen: ["queen_of_spades2.svg", "queen_of_spades.svg"],
  jack: ["jack_of_clubs2.svg", "jack_of_clubs.svg"],
  spade: ["ace_of_spades2.svg"],
  heart: ["ace_of_hearts.svg"],
  diamond: ["ace_of_diamonds.svg", "ace_of_diamonds2.svg"],
  club: ["ace_of_clubs.svg", "ace_of_clubs2.svg"],
};

function hasPack() {
  return fs.existsSync(SVG_DIR) && fs.readdirSync(SVG_DIR).some((f) => f.endsWith(".svg"));
}

function stripEditorMetadata(svg) {
  return svg
    .replace(/<\?xml[^?]*\?>\s*/g, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<(inkscape|sodipodi|rdf|cc|dc):[^>]*>[\s\S]*?<\/(inkscape|sodipodi|rdf|cc|dc):[^>]+>/g, "")
    .replace(/\s+xmlns:(inkscape|sodipodi|rdf|cc|dc)="[^"]*"/g, "")
    .replace(/\s+(inkscape|sodipodi):[a-zA-Z-]+="[^"]*"/g, "");
}

/** Heuristic: court art has many paths + skin-tone fills; plain suits are sparse. */
function inspectKind(file, svg) {
  const paths = (svg.match(/<path\b/g) || []).length;
  const skin = /#f9dcc4|#ffdbac|#e8b88a|#f5c99b/i.test(svg);
  const kind = paths > 40 || skin ? "court-figure" : "plain-suit";
  return { file, paths, skin, kind };
}

function main() {
  if (!hasPack()) {
    console.log("PACK MISSING — placeholders stay.");
    console.log(`Unzip the deck to: ${SRC_DIR}`);
    console.log("Then re-run: node scripts/build-ace-card-art.cjs");
    return;
  }
  const files = fs.readdirSync(SVG_DIR).filter((f) => f.endsWith(".svg"));
  console.log(`Found ${files.length} SVGs in ${SVG_DIR}.`);
  const rows = [];
  for (const [symbol, candidates] of Object.entries(WANT)) {
    let picked = null;
    for (const c of candidates) {
      const p = path.join(SVG_DIR, c);
      if (!fs.existsSync(p)) continue;
      const raw = fs.readFileSync(p, "utf8");
      const clean = stripEditorMetadata(raw);
      const info = inspectKind(c, clean);
      rows.push({ symbol, ...info, bytes: clean.length });
      // courts want court-figure; suits want plain-suit
      const wantCourt = ["king", "queen", "jack", "ace"].includes(symbol);
      if (!picked || (wantCourt ? info.kind === "court-figure" : info.kind === "plain-suit")) {
        picked = { file: c, svg: clean, info };
        if (wantCourt === (info.kind === "court-figure")) break;
      }
    }
    if (picked) {
      console.log(`MAP ${symbol} <- ${picked.file} (${picked.info.kind}, ${picked.info.paths} paths)`);
    } else {
      console.log(`MAP ${symbol} <- MISSING (candidates: ${candidates.join(", ")})`);
    }
  }
  if (!fs.existsSync(ART_DIR)) fs.mkdirSync(ART_DIR, { recursive: true });
  const md = [
    "# Royale Ace card-art mapping (generated by scripts/build-ace-card-art.mjs)",
    "",
    "| symbol | source svg | kind | paths |",
    "|---|---|---|---|",
    ...rows.map((r) => `| ${r.symbol} | ${r.file} | ${r.kind} | ${r.paths} |`),
    "",
    "Court art = framed portrait panel, mirrored bottom-right index dropped.",
    "Suit colors from CSS vars; court palettes fixed.",
  ].join("\n");
  fs.writeFileSync(path.join(ART_DIR, "MAPPING.md"), md);
  console.log(`Wrote ${path.join(ART_DIR, "MAPPING.md")}`);
  console.log("Next: emit React components + WebP fallbacks (needs svgo/sharp — see header).");
  console.log("Then flip ACE_ART_PLACEHOLDER to false in art/index.ts (manual confirm).");
}

main();
