/**
 * Value objects shared between TanvionRoyale and a licensed operator.
 *
 * Every external entity carries `externalProvider` + `externalId` because
 * external IDs are never assumed to be globally unique.
 */

import type { MinorUnit } from '@tanvion-royale/types';

export interface ProviderEntity {
  externalProvider: string;
  externalId: string;
}

export interface ProviderSport {
  externalProvider: string;
  externalId: string;
  name: string;
  active: boolean;
}

export interface ProviderCompetition {
  externalProvider: string;
  externalId: string;
  sport: ProviderSport;
  name: string;
  country: string | null;
}

export type EventStatus = 'PREMATCH' | 'LIVE' | 'UPCOMING' | 'FINISHED' | 'SUSPENDED' | 'CANCELLED';

export interface ProviderEvent {
  externalProvider: string;
  externalId: string;
  competition: ProviderCompetition;
  kicksOffAt: string; // ISO 8601
  homeName: string;
  awayName: string;
  status: EventStatus;
  live: boolean;
}

export interface ProviderMarket {
  externalProvider: string;
  externalId: string;
  event: ProviderEvent;
  name: string; // e.g. "Match Winner"
}

export interface ProviderSelection {
  externalProvider: string;
  externalId: string;
  market: ProviderMarket;
  name: string; // e.g. "Team A"
}

export interface ProviderOdd {
  externalProvider: string;
  externalId: string;
  selection: ProviderSelection;
  decimal: string; // decimal string to avoid float drift
  status: 'OPEN' | 'SUSPENDED' | 'CLOSED' | 'REMOVED';
  updatedAt: string;
}

export type BetType = 'SINGLE' | 'MULTIPLE' | 'SYSTEM';

export interface PlaceBetRequest {
  accountRef: string;
  type: BetType;
  stake: MinorUnit;
  currency: string;
  selections: Array<{
    externalSelectionId: string;
    requestedDecimal: string;
  }>;
  /** Idempotency key generated by TanvionRoyale and forwarded to the operator. */
  idempotencyKey: string;
}

export type BetAcceptedStatus = 'ACCEPTED' | 'REJECTED' | 'SUSPENDED' | 'EXPIRED' | 'PENDING';

export interface PlaceBetResult {
  externalBetId: string;
  status: BetAcceptedStatus;
  acceptedOdds: string | null;
  potentialReturn: MinorUnit | null;
  message: string | null;
  raw: unknown;
}

export type ProviderBalanceStatus = 'AVAILABLE' | 'BONUS' | 'PENDING' | 'WITHDRAWABLE';

export interface ProviderBalance {
  currency: string;
  available: MinorUnit;
  bonus: MinorUnit;
  pending: MinorUnit;
  withdrawable: MinorUnit;
}

export type ProviderTransactionKind =
  | 'DEPOSIT'
  | 'WITHDRAWAL'
  | 'BET'
  | 'BET_WIN'
  | 'BET_REFUND'
  | 'BONUS'
  | 'ADJUSTMENT';

export type ProviderTransactionStatus =
  | 'CREATED'
  | 'PENDING'
  | 'PROCESSING'
  | 'SUCCESS'
  | 'FAILED'
  | 'CANCELLED'
  | 'REFUNDED';

export interface ProviderTransaction {
  externalTransactionId: string;
  kind: ProviderTransactionKind;
  amount: MinorUnit;
  /** Signed value: positive for credits, negative for debits. */
  signedAmount: MinorUnit;
  currency: string;
  status: ProviderTransactionStatus;
  createdAt: string;
}

export type WebhookEventType =
  | 'bet.updated'
  | 'deposit.updated'
  | 'withdrawal.updated'
  | 'settlement.created';

export interface ProviderWebhookEvent {
  type: WebhookEventType;
  eventId: string;
  providerProjectId: string;
  occurredAt: string;
  payload: Record<string, unknown>;
}